-- Replaces the old Hibernate-generated barber table (no ownership/shop model).
DROP TABLE IF EXISTS barber;

CREATE TABLE barbers (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE,
    shop_id          BIGINT,
    bio              VARCHAR(1000),
    experience_years INTEGER CHECK (experience_years >= 0),
    specialty        VARCHAR(100),
    address          VARCHAR(255),
    city             VARCHAR(100),
    latitude         DOUBLE PRECISION,
    longitude        DOUBLE PRECISION,
    status           VARCHAR(20)  NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'SUSPENDED')),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE shops (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id     BIGINT       NOT NULL REFERENCES barbers (id) ON DELETE CASCADE,
    name         VARCHAR(100) NOT NULL,
    address      VARCHAR(255) NOT NULL,
    city         VARCHAR(100) NOT NULL,
    phone_number VARCHAR(30),
    latitude     DOUBLE PRECISION,
    longitude    DOUBLE PRECISION,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- A barber with no shop works independently.
ALTER TABLE barbers
    ADD CONSTRAINT fk_barbers_shop FOREIGN KEY (shop_id) REFERENCES shops (id) ON DELETE SET NULL;

CREATE INDEX idx_barbers_shop ON barbers (shop_id);
CREATE INDEX idx_shops_city ON shops (city);

CREATE TABLE service_offerings (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barber_id        BIGINT        NOT NULL REFERENCES barbers (id) ON DELETE CASCADE,
    name             VARCHAR(100)  NOT NULL,
    description      VARCHAR(500),
    duration_minutes INTEGER       NOT NULL CHECK (duration_minutes BETWEEN 5 AND 480),
    price            NUMERIC(8, 2) NOT NULL CHECK (price >= 0),
    -- Services are deactivated instead of deleted so future appointments keep a valid reference.
    active           BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_service_offerings_barber ON service_offerings (barber_id);

-- Several rows per day allow split shifts (e.g. 10:00-14:00 and 17:00-21:00).
CREATE TABLE working_hours (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barber_id   BIGINT      NOT NULL REFERENCES barbers (id) ON DELETE CASCADE,
    day_of_week VARCHAR(10) NOT NULL
        CHECK (day_of_week IN ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
    start_time  TIME        NOT NULL,
    end_time    TIME        NOT NULL,
    CHECK (start_time < end_time)
);

CREATE INDEX idx_working_hours_barber ON working_hours (barber_id);
