-- Matches the users table Hibernate generated before Flyway was introduced.
-- Existing databases are baselined at this version, so this only runs on fresh databases.
CREATE TABLE users (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255),
    email        VARCHAR(255) NOT NULL UNIQUE,
    phone_number VARCHAR(255),
    password     VARCHAR(255),
    role         VARCHAR(255) CHECK (role IN ('CUSTOMER', 'BARBER', 'ADMIN'))
);
