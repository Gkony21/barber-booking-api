-- The barber's own notes about a customer (e.g. "νο 1 στο πλάι"). Customers never see them.
-- A customer is identified by their mobile number (or name, for walk-ins without one); see ClientKeys.
CREATE TABLE client_notes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barber_id  BIGINT        NOT NULL REFERENCES barbers (id) ON DELETE CASCADE,
    client_key VARCHAR(120)  NOT NULL,
    note       VARCHAR(1000) NOT NULL,
    updated_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_client_notes UNIQUE (barber_id, client_key)
);
