-- Profile photo: the storage key of a square JPEG, or null.
ALTER TABLE barbers ADD COLUMN avatar_key VARCHAR(100);

-- Photos of the barber's work, shown to customers (at most 20 per barber, enforced by the app).
CREATE TABLE barber_photos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barber_id  BIGINT       NOT NULL REFERENCES barbers (id) ON DELETE CASCADE,
    image_key  VARCHAR(100) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_barber_photos_barber ON barber_photos (barber_id, created_at);
