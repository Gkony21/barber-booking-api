-- A shop owner invites a barber; the barber joins only by accepting. Before this, an owner could
-- add any barber to their shop without asking.
CREATE TABLE shop_invitations (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id      BIGINT      NOT NULL REFERENCES shops (id) ON DELETE CASCADE,
    barber_id    BIGINT      NOT NULL REFERENCES barbers (id) ON DELETE CASCADE,
    status       VARCHAR(20) NOT NULL
        CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'CANCELLED')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    responded_at TIMESTAMPTZ
);

-- At most one open invitation per shop and barber.
CREATE UNIQUE INDEX uq_shop_invitations_pending ON shop_invitations (shop_id, barber_id) WHERE status = 'PENDING';
CREATE INDEX idx_shop_invitations_barber ON shop_invitations (barber_id, status);
