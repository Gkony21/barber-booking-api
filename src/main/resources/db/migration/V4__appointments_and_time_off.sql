-- Lets an exclusion constraint combine "same barber" (=) with "overlapping time" (&&).
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- When false, new bookings wait for the barber to confirm them.
ALTER TABLE barbers ADD COLUMN auto_confirm_bookings BOOLEAN NOT NULL DEFAULT TRUE;

-- Whole days the barber is unavailable (holidays, days off). Both dates are inclusive.
CREATE TABLE time_off (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barber_id  BIGINT       NOT NULL REFERENCES barbers (id) ON DELETE CASCADE,
    start_date DATE         NOT NULL,
    end_date   DATE         NOT NULL,
    reason     VARCHAR(255),
    CHECK (start_date <= end_date)
);

CREATE INDEX idx_time_off_barber ON time_off (barber_id, start_date);

CREATE TABLE appointments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    barber_id       BIGINT        NOT NULL REFERENCES barbers (id) ON DELETE CASCADE,
    service_id      BIGINT        NOT NULL REFERENCES service_offerings (id),
    -- Name and price are copied at booking time so later edits to the service do not change past bookings.
    service_name    VARCHAR(100)  NOT NULL,
    price           NUMERIC(8, 2) NOT NULL,
    start_at        TIMESTAMPTZ   NOT NULL,
    end_at          TIMESTAMPTZ   NOT NULL,
    status          VARCHAR(20)   NOT NULL
        CHECK (status IN ('PENDING', 'CONFIRMED', 'REJECTED', 'CANCELLED')),
    cancelled_by    VARCHAR(20)
        CHECK (cancelled_by IN ('CUSTOMER', 'BARBER')),
    customer_note   VARCHAR(500),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CHECK (start_at < end_at),

    -- The database itself refuses two active appointments of the same barber that overlap,
    -- even if two customers press "book" at the same moment.
    CONSTRAINT no_overlapping_appointments EXCLUDE USING gist (
        barber_id WITH =,
        tstzrange(start_at, end_at) WITH &&
    ) WHERE (status IN ('PENDING', 'CONFIRMED'))
);

CREATE INDEX idx_appointments_barber_start ON appointments (barber_id, start_at);
CREATE INDEX idx_appointments_customer_start ON appointments (customer_id, start_at);
