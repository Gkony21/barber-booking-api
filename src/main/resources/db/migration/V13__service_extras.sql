-- A barber's services are either main services/packages (the customer picks one) or extras
-- (added on top, any number). Existing services become main services.
ALTER TABLE service_offerings ADD COLUMN kind VARCHAR(10) NOT NULL DEFAULT 'MAIN'
    CHECK (kind IN ('MAIN', 'EXTRA'));

-- Extras chosen with an appointment, copied at booking time like the main service's name and
-- price. appointments.price is the total; the appointment's length already includes the extras.
CREATE TABLE appointment_extras (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id   BIGINT        NOT NULL REFERENCES appointments (id) ON DELETE CASCADE,
    service_id       BIGINT        NOT NULL REFERENCES service_offerings (id),
    name             VARCHAR(100)  NOT NULL,
    price            NUMERIC(8, 2) NOT NULL,
    duration_minutes INTEGER       NOT NULL,
    position         INTEGER       NOT NULL
);

CREATE INDEX idx_appointment_extras_appointment ON appointment_extras (appointment_id);
